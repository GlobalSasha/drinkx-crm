"""Какие лиды ещё не сделка — для счётчика «застряло 7+ дней».

Как работает рабочая воронка: новая заявка встаёт на самый левый столбец
«Не отвечает» (до клиента ещё не дозвонились), обработанную менеджер
переводит на «Первый контакт». Оба этапа — ещё не сделка: такие лиды идут в
сводке отдельной строкой, а не в «застрявших сделках».

Куда заводятся новые лиды и где заявка числится во «Входящих» — это
по-прежнему самый левый столбец (get_default_first_stage, forms/inbox.py),
здесь он не меняется. PR #248 на сутки перенёс и его — так делать нельзя.

Правило: ещё не сделка — этап с «не отвеча» в названии и самый левый из
остальных незакрытых этапов. В воронке без «Не отвечает» это просто первый
этап.
"""
from __future__ import annotations

PARKING_MARK = "не отвеча"

# Этап лида в сыром запросе зовётся `s`.
NOT_A_DEAL_YET_SQL = f"""(
    lower(s.name) LIKE '%{PARKING_MARK}%'
    OR s.position = (
        SELECT min(s2.position) FROM stages s2
        WHERE s2.pipeline_id = s.pipeline_id
          AND s2.is_won = false AND s2.is_lost = false
          AND lower(s2.name) NOT LIKE '%{PARKING_MARK}%'
    )
)"""
